@dataclasses.dataclass(frozen=True)
class NoiseParams:
    """
    Everything a noise kernel needs, in a fixed order.

    :param seed: Integer seed; wrapped to int32 by the kernels exactly as the reference does.
    :param frequency: Coordinate scale applied before everything else.
    :param noise_type: Base noise function.
    :param fractal_type: Octave accumulation. ``NONE`` samples once.
    :param octaves: Octave count; ignored when ``fractal_type`` is ``NONE``. Never below 1.
    :param lacunarity: Frequency multiplier per octave.
    :param gain: Amplitude multiplier per octave.
    :param weighted_strength: Octave weighting by the previous octave's value, 0 disables.
    :param ping_pong_strength: Fold strength for ``PING_PONG``.
    :param rotation_3d: 3D rotation choice; ``NONE`` lets the noise type pick its default.
    :param cellular_distance: Metric for ``CELLULAR``; the reference default is ``EUCLIDEAN_SQ``.
    :param cellular_return: What ``CELLULAR`` returns; the reference default is ``DISTANCE``.
    :param cellular_jitter: Cell point jitter for ``CELLULAR``, 1.0 is the reference default.
    :param cellular_lookup_type: For the ``NOISE_LOOKUP`` return: the noise sampled at the nearest cell
        point (any type but cellular). FastNoiseSIMD's, Phase C.
    :param cellular_lookup_frequency: That lookup's frequency over the cell point; 0.2 is FastNoiseSIMD's default.
    :param domain_warp: Warp the raw coordinates before the noise (the reference's ``DomainWarp`` then
        ``GetNoise``); ``NONE`` is off. Frequency, seed, octaves, gain and lacunarity are shared with
        the noise, as in the reference. With ``fractal_type`` ``DOMAIN_WARP_PROGRESSIVE`` or
        ``DOMAIN_WARP_INDEPENDENT`` the warp runs its octaves and the noise samples once, exactly the
        reference's split; with any other fractal the warp is a single step and the noise keeps its octaves.
    :param domain_warp_amp: Warp amplitude in coordinate units, scaled by `fractal_bounding` like the reference.
    :param perturb: FastNoiseSIMD's gradient perturb on the frequency-scaled point (Phase C); ``NONE`` is off.
    :param perturb_amp: Its amplitude, in frequency-scaled units (1.0 is one lattice cell of the noise).
    :param perturb_frequency: The perturb lattice's frequency relative to the noise's; 0.5 is FNS's default.
    :param perturb_octaves: Octaves for the fractal perturb modes; with `perturb_lacunarity` and `perturb_gain`.
    :param perturb_normalise_length: For the normalise modes, the point's length in coordinate units after.
    """

    seed: int = 1337
    frequency: float = 0.01
    noise_type: NoiseType = NoiseType.OPEN_SIMPLEX2
    fractal_type: FractalType = FractalType.NONE
    octaves: int = 3
    lacunarity: float = 2.0
    gain: float = 0.5
    weighted_strength: float = 0.0
    ping_pong_strength: float = 2.0
    rotation_3d: Rotation3D = Rotation3D.NONE
    cellular_distance: CellularDistance = CellularDistance.EUCLIDEAN_SQ
    cellular_return: CellularReturn = CellularReturn.DISTANCE
    cellular_jitter: float = 1.0
    domain_warp: DomainWarpType = DomainWarpType.NONE
    domain_warp_amp: float = 1.0
    perturb: PerturbType = PerturbType.NONE
    perturb_amp: float = 1.0
    perturb_frequency: float = 0.5
    perturb_octaves: int = 3
    perturb_lacunarity: float = 2.0
    perturb_gain: float = 0.5
    perturb_normalise_length: float = 1.0
    cellular_lookup_type: NoiseType = (
        NoiseType.OPEN_SIMPLEX2
    )  # after the fields that predate it: positional callers keep their order
    cellular_lookup_frequency: float = 0.2

    def __post_init__(self) -> None:
        object.__setattr__(self, "noise_type", NoiseType(self.noise_type))
        object.__setattr__(self, "fractal_type", FractalType(self.fractal_type))
        object.__setattr__(self, "rotation_3d", Rotation3D(self.rotation_3d))
        object.__setattr__(self, "domain_warp", DomainWarpType(self.domain_warp))
        object.__setattr__(self, "perturb", PerturbType(self.perturb))
        object.__setattr__(self, "perturb_octaves", max(1, int(self.perturb_octaves)))
        object.__setattr__(self, "cellular_distance", CellularDistance(self.cellular_distance))
        object.__setattr__(self, "cellular_return", CellularReturn(self.cellular_return))
        object.__setattr__(self, "cellular_lookup_type", NoiseType(self.cellular_lookup_type))
        if self.cellular_lookup_type == NoiseType.CELLULAR:
            raise ValueError("cellular_lookup_type cannot be cellular itself")
        object.__setattr__(self, "octaves", max(1, int(self.octaves)))
        object.__setattr__(self, "seed", int(self.seed))
        if self.noise_type not in IMPLEMENTED_NOISE_TYPES:
            raise NotImplementedError(
                f"{self.noise_type.name} is scheduled for {_UNIMPLEMENTED_REASON[self.noise_type]}"
            )
        if self.fractal_type not in IMPLEMENTED_FRACTAL_TYPES:
            raise NotImplementedError(
                f"{self.fractal_type.name} is scheduled for {_UNIMPLEMENTED_REASON[self.fractal_type]}"
            )

    @property
    def fractal_bounding(self) -> float:
        """The reference's ``mFractalBounding``: normalises an octave sum back to about [-1, 1]."""
        gain = abs(self.gain)
        amp = gain
        amp_fractal = 1.0
        for _ in range(1, self.octaves):
            amp_fractal += amp
            amp *= gain
        return 1.0 / amp_fractal

    @property
    def transform_3d(self) -> Transform3D:
        """The reference's ``UpdateTransformType3D``."""
        if self.rotation_3d == Rotation3D.IMPROVE_XY_PLANES:
            return Transform3D.IMPROVE_XY_PLANES
        if self.rotation_3d == Rotation3D.IMPROVE_XZ_PLANES:
            return Transform3D.IMPROVE_XZ_PLANES
        if self.noise_type in (NoiseType.OPEN_SIMPLEX2, NoiseType.OPEN_SIMPLEX2S):
            return Transform3D.DEFAULT_OPEN_SIMPLEX2
        return Transform3D.NONE

    @property
    def warp_transform_3d(self) -> Transform3D:
        """The reference's ``UpdateWarpTransformType3D``: the rotation if set, else by warp type."""
        if self.rotation_3d == Rotation3D.IMPROVE_XY_PLANES:
            return Transform3D.IMPROVE_XY_PLANES
        if self.rotation_3d == Rotation3D.IMPROVE_XZ_PLANES:
            return Transform3D.IMPROVE_XZ_PLANES
        if self.domain_warp in (DomainWarpType.OPEN_SIMPLEX2, DomainWarpType.OPEN_SIMPLEX2_REDUCED):
            return Transform3D.DEFAULT_OPEN_SIMPLEX2
        return Transform3D.NONE

    @property
    def noise_fractal_type(self) -> FractalType:
        """What the noise itself accumulates: the domain-warp fractals leave the noise single-octave."""
        if self.fractal_type in (FractalType.DOMAIN_WARP_PROGRESSIVE, FractalType.DOMAIN_WARP_INDEPENDENT):
            return FractalType.NONE
        return self.fractal_type

    @property
    def warp_fractal(self) -> int:
        """How the warp applies its octaves: 0 single, 1 progressive, 2 independent (`scalar.WARP_*`)."""
        if self.fractal_type == FractalType.DOMAIN_WARP_PROGRESSIVE:
            return 1
        if self.fractal_type == FractalType.DOMAIN_WARP_INDEPENDENT:
            return 2
        return 0

    def kernel_args(
        self,
    ) -> Tuple[Union[int, float], ...]:
        """
        The positional scalars every kernel takes, in the one order they take them.

        Order: ``seed, frequency, noise_type, fractal_type, octaves, lacunarity, gain,
        weighted_strength, ping_pong_strength, fractal_bounding, cellular_distance,
        cellular_return, cellular_jitter, transform_3d, domain_warp, warp_amp, warp_fractal,
        warp_transform_3d, cellular_lookup_type, cellular_lookup_frequency, perturb, perturb_amp,
        perturb_frequency, perturb_octaves, perturb_lacunarity, perturb_gain, perturb_normalise_length``.
        ``fractal_type`` here is
        `noise_fractal_type`; ``warp_amp`` is the
        amplitude already scaled by `fractal_bounding`. The 2D kernels take everything but the two
        transforms; `KERNEL_ARGS_2D` is the count they take after the coordinate arrays.
        """
        return (
            self.seed,
            float(self.frequency),
            int(self.noise_type),
            int(self.noise_fractal_type),
            self.octaves,
            float(self.lacunarity),
            float(self.gain),
            float(self.weighted_strength),
            float(self.ping_pong_strength),
            self.fractal_bounding,
            int(self.cellular_distance),
            int(self.cellular_return),
            float(self.cellular_jitter),
            int(self.transform_3d),
            int(self.domain_warp),
            float(self.domain_warp_amp) * self.fractal_bounding,
            self.warp_fractal,
            int(self.warp_transform_3d),
            int(self.cellular_lookup_type),
            float(self.cellular_lookup_frequency),
            int(self.perturb),
            float(self.perturb_amp),
            float(self.perturb_frequency),
            self.perturb_octaves,
            float(self.perturb_lacunarity),
            float(self.perturb_gain),
            float(self.perturb_normalise_length),
        )

    def replace(self, **changes: object) -> "NoiseParams":
        """A copy with fields changed, validated like a fresh construction."""
        return dataclasses.replace(self, **changes)



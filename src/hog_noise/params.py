"""
HogNoise: noise kernel parameters and the names callers use for them.
Package: hog_noise/params

`NoiseParams` is the one parameter record every rung of the noise ladder consumes: the numpy base,
the numba kernel, and later a WGSL uniform. It is frozen, fields are fixed-width numbers in a fixed
order, and enums are integers, so a kernel signature never grows a positional argument per feature
and the same record can be laid out as a GPU uniform buffer without translation.

Enum values follow FastNoiseLite's declaration order so a vector generated by `pyfastnoiselite`
and a kernel here are talking about the same thing by number, not by name.
"""

import dataclasses
import logging as _logging
from enum import IntEnum
from typing import Dict, Tuple, Union

_MODULE_NAME = "hog_noise.params"
__version__ = "0.1.0"
__updated__ = "2026-09-13"
_LOGGER = _logging.getLogger(_MODULE_NAME)


class NoiseType(IntEnum):
    """Base noise function. Values match ``FastNoiseLite::NoiseType``."""

    OPEN_SIMPLEX2 = 0
    OPEN_SIMPLEX2S = 1
    CELLULAR = 2
    PERLIN = 3
    VALUE_CUBIC = 4
    VALUE = 5
    WHITE_NOISE = 6  # FastNoiseSIMD's (Phase C); past FastNoiseLite's range, which has none
    SIMPLEX_CLASSIC = 7  # FastNoiseSIMD's Simplex (Phase C): its hash, so old seeds reproduce by name


class FractalType(IntEnum):
    """Octave accumulation. Values match ``FastNoiseLite::FractalType``."""

    NONE = 0
    FBM = 1
    RIDGED = 2
    PING_PONG = 3
    DOMAIN_WARP_PROGRESSIVE = 4
    DOMAIN_WARP_INDEPENDENT = 5
    BILLOW = 6  # FastNoiseSIMD's (Phase C); past FastNoiseLite's range, which has no billow
    RIGID_MULTI = 7  # FastNoiseSIMD's RigidMulti (Phase C): 1 - |n|, later octaves subtracted, unnormalised; not Ridged


class Rotation3D(IntEnum):
    """3D coordinate rotation. Values match ``FastNoiseLite::RotationType3D``."""

    NONE = 0
    IMPROVE_XY_PLANES = 1
    IMPROVE_XZ_PLANES = 2


class DomainWarpType(IntEnum):
    """
    Domain warp function (Phase B). ``NONE`` is off; the others are ``FastNoiseLite::DomainWarpType``
    plus one, so the kernels test a single integer.
    """

    NONE = 0
    OPEN_SIMPLEX2 = 1
    OPEN_SIMPLEX2_REDUCED = 2
    BASIC_GRID = 3


class PerturbType(IntEnum):
    """
    FastNoiseSIMD's gradient perturb (Phase C), applied to the frequency-scaled point before the noise.
    Values match ``FastNoiseSIMD::PerturbType``. Distinct from `DomainWarpType`, FastNoiseLite's warp on
    the raw point; both may be set, and the warp runs first.
    """

    NONE = 0
    GRADIENT = 1
    GRADIENT_FRACTAL = 2
    NORMALISE = 3
    GRADIENT_NORMALISE = 4
    GRADIENT_FRACTAL_NORMALISE = 5


class CellularDistance(IntEnum):
    """Cellular distance metric. Values match ``FastNoiseLite::CellularDistanceFunction``."""

    EUCLIDEAN = 0
    EUCLIDEAN_SQ = 1
    MANHATTAN = 2
    HYBRID = 3
    NATURAL = 4  # FastNoiseSIMD's (Phase C): manhattan times euclidean squared, its distance form


class CellularReturn(IntEnum):
    """What a cellular sample returns. Values match ``FastNoiseLite::CellularReturnType``."""

    CELL_VALUE = 0
    DISTANCE = 1
    DISTANCE2 = 2
    DISTANCE2_ADD = 3
    DISTANCE2_SUB = 4
    DISTANCE2_MUL = 5
    DISTANCE2_DIV = 6
    NOISE_LOOKUP = 7  # FastNoiseSIMD's (Phase C): the lookup noise at the nearest cell point
    DISTANCE2_CAVE = 8  # FastNoiseSIMD's (Phase C): the lesser of two Distance2Div fields


class Transform3D(IntEnum):
    """Resolved 3D transform, derived from `Rotation3D` and `NoiseType` like the reference does."""

    NONE = 0
    IMPROVE_XY_PLANES = 1
    IMPROVE_XZ_PLANES = 2
    DEFAULT_OPEN_SIMPLEX2 = 3



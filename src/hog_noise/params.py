def parse_noise_type(name: str) -> NoiseType:
    """
    Resolve a caller-facing noise name.

    :param name: One of the keys of `NOISE_TYPE_NAMES`, case-insensitive.
    :return: The enum value.
    :raises ValueError: For an unknown name.
    :raises NotImplementedError: For a known name whose kernel has not been ported yet.
    """
    key = name.lower()
    if key not in NOISE_TYPE_NAMES:
        raise ValueError(f"Unknown noise type {name!r}; expected one of {sorted(NOISE_TYPE_NAMES)}")
    value = NOISE_TYPE_NAMES[key]
    if value not in IMPLEMENTED_NOISE_TYPES:
        raise NotImplementedError(f"Noise type {name!r} is scheduled for {_UNIMPLEMENTED_REASON[value]}")
    return value


def parse_fractal_type(name: str) -> FractalType:
    """
    Resolve a caller-facing fractal name.

    :param name: One of the keys of `FRACTAL_TYPE_NAMES`, case-insensitive.
    :return: The enum value.
    :raises ValueError: For an unknown name.
    :raises NotImplementedError: For a known name whose kernel is still scheduled (none today).
    """
    key = name.lower()
    if key not in FRACTAL_TYPE_NAMES:
        raise ValueError(f"Unknown fractal type {name!r}; expected one of {sorted(FRACTAL_TYPE_NAMES)}")
    value = FRACTAL_TYPE_NAMES[key]
    if value not in IMPLEMENTED_FRACTAL_TYPES:
        raise NotImplementedError(f"Fractal type {name!r} is scheduled for {_UNIMPLEMENTED_REASON[value]}")
    return value



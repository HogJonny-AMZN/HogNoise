"""
Framework: the commit-message check: no AI attribution, and an accepted sign-off when the project requires one.
Package: tools/check_commit_msg

Run by the ``commit-msg`` git hook with the path of the message file; a message that breaks either rule stops the
commit. The rules are the definition of done's *Identity* section (``Docs/standards/definition-of-done.md``):

* **No AI attribution.** Commits carry a person's identity, never an agent's. A ``Co-Authored-By`` trailer naming an
  AI, or a ``Generated with`` / ``Generated by`` footer naming one (the name list is a floor, in ``AI_NAMES``), is
  rejected: that is what tools add by default and what the project has decided not to carry.
* **The sign-off.** When ``signoff`` is true in ``project.json``, the message must hold a ``Signed-off-by:`` line
  carrying an accepted identity: the owner's name and email from ``project.json``, or a roster person's ``name`` and
  one of their ``emails`` (``[[people]]`` in ``framework.toml``; a person with no address cannot sign). The email is
  compared without regard to case, the name exactly. ``git commit -s`` writes it. A repository with no
  ``framework.toml`` accepts the owner alone; one whose ``framework.toml`` cannot be read or is invalid stops the
  hook (exit 2), never narrowing to the owner silently.

A line starting with ``#`` is read like any other for attribution (git keeps it when the message is given with
``-m``) and counts for nothing as a sign-off. A merge, ``fixup!``, ``squash!`` or ``amend!`` message needs no
sign-off of its own. Run standalone (exit code 0 accepted, 1 rejected with the reasons printed, 2 the message file,
``project.json`` or ``framework.toml`` is unusable)::

    uv run python tools/check_commit_msg.py [-v] [--root PATH] MESSAGE_FILE
"""

from __future__ import annotations

import argparse
import logging as _logging
import re
import sys
from pathlib import Path

import framework_config as fc

# -------------------------------------------------------------------------
# module global scope
_MODULE_NAME = "tools.check_commit_msg"
__version__ = "0.2.0"
__updated__ = "2026-10-29"
_LOGGER = _logging.getLogger(_MODULE_NAME)

ROOT = Path(__file__).resolve().parent.parent

#: Names that mark a trailer or footer as an AI's, matched as whole words without regard to case. A floor, not a list of
#: every tool: a new one is added here when it first appears in a trailer. A person who shares a name with one of
#: these cannot be named in a ``Co-Authored-By`` trailer; that is the price of a name list, and the remedy is to name
#: them in the message body.
AI_NAMES = (
    "claude",
    "anthropic",
    "copilot",
    "gemini",
    "openai",
    "chatgpt",
    "gpt",
    "codex",
    "cursor",
    "devin",
    "aider",
    "windsurf",
    "codeium",
)
_AI_RE = re.compile(r"\b(" + "|".join(AI_NAMES) + r")\b|\[bot\]|noreply@anthropic\.com", re.IGNORECASE)
#: A comment line (``#``) is read like any other: git keeps it when the message is given with ``-m``, so a commented-out
#: attribution would ship. The hook errs toward rejecting.
_TRAILER_RE = re.compile(r"^\s*#?\s*(co-authored-by|assisted-by|generated-by)\s*:(.*)$", re.IGNORECASE)
_GENERATED_RE = re.compile(r"^\s*#?\s*(?:[^\w\s#]\s*)?generated[\s-]+(?:with|by)\b", re.IGNORECASE)
_SIGNOFF_RE = re.compile(r"^\s*signed-off-by\s*:\s*(.*?)\s*<([^<>]*)>\s*$", re.IGNORECASE)
#: Messages git writes itself, or that a rebase folds away, and that need no sign-off of their own.
_SIGNOFF_EXEMPT = (
    "merge branch ",
    "merge branches ",
    "merge remote-tracking branch ",
    "merge remote-tracking branches ",
    "merge pull request ",
    "merge tag ",
    "merge tags ",
    "merge commit ",
    "fixup! ",
    "squash! ",
    "amend! ",
)


def _first_line(message: str) -> str:
    return next((line.strip() for line in message.splitlines() if line.strip()), "")


def accepted_identities(project: fc.ProjectConfig, people: tuple[fc.Person, ...] = ()) -> list[tuple[str, str, str]]:
    """The ``(name, email, source)`` triples a sign-off may carry: the owner, then each roster address.

    A roster person with no ``emails`` contributes nothing: the row says which addresses they commit with, and an
    absent list is an absent answer, not a wildcard. The owner's own roster row repeats the owner's identity, so a
    name and address already listed (the address compared without regard to case) is not listed twice.

    :param project: The project's identity (``project.json``).
    :param people: The roster (``[[people]]`` in ``framework.toml``), empty where there is none.
    """
    identities = [(project.owner.name, project.owner.email, "the owner, project.json")]
    for person in people:
        for email in person.emails:
            if all((person.name, email.casefold()) != (n, e.casefold()) for n, e, _ in identities):
                identities.append((person.name, email, f"the roster, framework.toml: @{person.login}"))
    return identities


def check_message(message: str, project: fc.ProjectConfig, people: tuple[fc.Person, ...] = ()) -> list[str]:
    """The reasons ``message`` must be rejected, empty when it is accepted.

    :param message: The commit message text.
    :param project: The project's identity and whether it requires a sign-off.
    :param people: The roster whose members may sign as themselves; empty where the repository has none.
    """
    found: list[str] = []
    lines = message.splitlines()
    for line in lines:
        trailer = _TRAILER_RE.match(line)
        generated = _GENERATED_RE.match(line)
        if trailer and _AI_RE.search(trailer.group(2)):
            found.append(f"an AI attribution trailer is not allowed: {line.strip()!r}")
        elif generated and _AI_RE.search(line[generated.end() :]):
            found.append(f"a 'Generated with/by' footer naming an AI is not allowed: {line.strip()!r}")
    if project.signoff and not _first_line(message).lower().startswith(_SIGNOFF_EXEMPT):
        identities = accepted_identities(project, people)
        signed = any(
            (m := _SIGNOFF_RE.match(line))
            and any(m.group(1) == name and m.group(2).casefold() == email.casefold() for name, email, _ in identities)
            for line in lines
        )
        if not signed:
            listed = "\n".join(
                f"    Signed-off-by: {name} <{email}>    ({source})" for name, email, source in identities
            )
            found.append(
                "the sign-off is missing or is not an accepted identity. git commit -s writes your git user.name and "
                f"user.email, so they must be one of:\n{listed}"
            )
    return found


def _roster(root: Path) -> tuple[fc.Person, ...]:
    """The roster of the repository at ``root``: empty when there is no ``framework.toml``.

    Three outcomes, never two: no file is no roster; a file that loads gives its people; a file that exists and cannot
    be read or is invalid raises ``ConfigError``, which stops the hook. Existence is tested first because
    ``load_framework`` reports an absent file as a ``ConfigError`` like any unreadable one.
    """
    path = root / "framework.toml"
    if not path.exists():
        _LOGGER.info(f"no framework.toml under {root}: the owner's sign-off alone")
        return ()
    return fc.load_framework(path).people


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("message_file", type=Path, help="the commit message file git hands the hook")
    parser.add_argument("--root", type=Path, default=ROOT, help="the repository whose project.json and roster apply")
    parser.add_argument("-v", "--verbose", action="store_true", help="log what was read to standard error")
    args = parser.parse_args(argv)
    _logging.basicConfig(
        level=_logging.INFO if args.verbose else _logging.WARNING, format="%(message)s", stream=sys.stderr
    )
    try:
        project = fc.load_project(args.root / "project.json")
        people = _roster(args.root)
        message = args.message_file.read_text(encoding="utf-8", errors="replace")
    except (fc.ConfigError, OSError) as e:
        print(f"commit-msg: cannot run: {e}", file=sys.stderr)
        return 2
    _LOGGER.info(
        f"read {args.message_file}: {len(message.splitlines())} line(s); signoff required: {project.signoff}; "
        f"accepted identities: {len(accepted_identities(project, people))}"
    )
    found = check_message(message, project, people)
    for reason in found:
        print(f"[commit-msg] {reason}", file=sys.stderr)
    if found:
        print("commit-msg: the commit was not made; fix the message and commit again", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

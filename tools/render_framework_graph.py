"""
Framework: the AI-first framework graph: validate the data and generate its page from it.
Package: tools/render_framework_graph

    uv run python tools/render_framework_graph.py --check    # CI: the graph is well formed and the page is current
    uv run python tools/render_framework_graph.py --write    # regenerate Docs/knowledge/ai-first-framework-graph.md

Exit code 0 clean, 1 findings (a malformed graph, a diagram too big for GitHub to draw, a stale page), 2 the data or
the page cannot be read or written. ``--root PATH`` points it at another repository (the default is the one this file
is in); ``-v`` logs what it read, checked and wrote to standard error.

The data is Docs/knowledge/ai-first-framework.graph.json: nodes (a generic artifact, concept, rule, check or
ritual of an AI-first repository, in one of eight layers) and typed edges between them, drawn from a closed set
of relations. It names no project; its `seen` field says in which repositories a node exists today. The page
is a Mermaid overview, one Mermaid diagram per layer, and a table of every node, so GitHub draws it and a
reader or an agent can query it without a viewer.
"""

from __future__ import annotations

import argparse
import difflib
import json
import logging as _logging
import os
import re
import sys
import tempfile
from collections import Counter
from pathlib import Path
from typing import Any

import log_setup

_MODULE_NAME = "tools.render_framework_graph"
__version__ = "0.3.0"
__updated__ = "2026-10-13"
_LOGGER = _logging.getLogger(_MODULE_NAME)

ROOT = Path(__file__).resolve().parents[1]
_KNOWLEDGE = Path("Docs") / "knowledge"
DATA = ROOT / _KNOWLEDGE / "ai-first-framework.graph.json"
PAGE = ROOT / _KNOWLEDGE / "ai-first-framework-graph.md"
HEADER = "<!-- generated by tools/render_framework_graph.py --write from ai-first-framework.graph.json; do not edit -->"

_ID_RE = re.compile(r"[a-z][a-z0-9]*(-[a-z0-9]+)*")
_LAYER_RE = re.compile(r"[a-z][a-z0-9]*")
#: GitHub draws a Mermaid diagram of at most 50,000 characters and 500 edges; refuse a layer diagram well short of that.
MAX_DIAGRAM_CHARS = 40_000
MAX_DIAGRAM_EDGES = 400
_SEEN_LETTERS = "HLST"  # H, L, S: the three repositories it was drawn from; T: first built in the template
_NODE_KEYS = ("id", "kind", "layer", "label", "seen", "summary")
_SHAPES = {
    "artifact": ("[", "]"),
    "concept": ("(", ")"),
    "rule": ("{{", "}}"),
    "check": ("[[", "]]"),
    "ritual": ("([", "])"),
}
_STYLE = {
    "artifact": "fill:#e8f0fe,stroke:#4a6fa5",
    "concept": "fill:#f3f3f3,stroke:#888",
    "rule": "fill:#fff4d6,stroke:#b8860b",
    "check": "fill:#e3f6e3,stroke:#3a7d3a",
    "ritual": "fill:#fde8f0,stroke:#a5476b",
}
_ARROWS = {
    "links-to": "-->",
    "reads": "-.->",
    "records": "-->",
    "feeds": "==>",
    "gates": "==>",
    "enforces": "-->",
    "mechanises": "==>",
    "constrains": "-.->",
    "defines": "-->",
    "annotates": "-.->",
}


_STATUS_LINE = (
    "**Status:** Living. Generated from `ai-first-framework.graph.json` by "
    "`tools/render_framework_graph.py --write`; edit the data, not this page."
)
_SEEN_LINE = (
    "Nothing here names a project. *Seen in* says where a concept existed when the framework was drawn: "
    "**H**, **L** and **S** are the three repositories it was extracted from."
)


def _relations_drawn(arrow: str) -> str:
    """The relations drawn with ``arrow``, as code spans: the legend is made from the same table the diagrams are."""
    return ", ".join(f"`{r}`" for r, a in _ARROWS.items() if a == arrow)


_READING = (
    "Shapes say what a node is: a rectangle is an artifact (a file or directory), a rounded box a concept, "
    "a hexagon a rule, a double-bordered box a check (it goes red), a stadium a ritual. Arrows say how: a thick "
    f"arrow is a flow that must happen ({_relations_drawn('==>')}), a plain arrow is a link or a record "
    f"({_relations_drawn('-->')}), a dotted arrow a read, a constraint or an annotation ({_relations_drawn('-.->')}). "
    "Every edge is labelled with its relation."
)
_BETWEEN = "Edge counts between layers; edges inside one layer are in the layer's own diagram below."


class GraphError(Exception):
    """The data file cannot be read or is not the shape this tool expects."""


def _no_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    """``object_pairs_hook`` that refuses a repeated key: JSON allows it and keeps the last, which hides an edit."""
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"the key {key!r} appears twice in one object")
        result[key] = value
    return result


def load(path: Path = DATA) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"), object_pairs_hook=_no_duplicate_keys)
    except (OSError, ValueError, RecursionError, MemoryError) as e:
        raise GraphError(f"cannot read {path}: {type(e).__name__}: {e}") from e
    if not isinstance(data, dict):
        raise GraphError(f"{path} is not a JSON object")
    nodes, edges = data.get("nodes"), data.get("edges")  # not yet validated: either may be anything
    _LOGGER.info(
        f"read {path}: {len(nodes) if isinstance(nodes, list) else '?'} node(s), "
        f"{len(edges) if isinstance(edges, list) else '?'} edge(s)"
    )
    return data


def _text(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _break_problem(value: str) -> str:
    """What is wrong with text that goes into a table cell, a heading or a diagram label: a pipe or a line break would
    break the table or let a fence or a heading in. Empty when the text is fine."""
    return "holds a pipe or a line break, which breaks the page" if any(c in value for c in "|\n\r") else ""


def _shape_problems(data: dict[str, Any]) -> list[str]:
    """The top-level shape: dicts where dicts belong, lists of objects, closed sets the renderer can draw."""
    found = [
        f"missing top-level key '{k}'" for k in ("layers", "kinds", "relations", "nodes", "edges") if k not in data
    ]
    if found:
        return found
    for key in ("layers", "kinds", "relations"):
        value = data[key]
        if not isinstance(value, dict) or not all(_text(k) and _text(v) for k, v in value.items()):
            found.append(f"'{key}' must be an object of non-empty strings")
        else:  # a layer title becomes a heading and a diagram label, a relation's meaning a table cell
            found += [f"{key} '{k}': the text {_break_problem(v)}" for k, v in value.items() if _break_problem(v)]
    for key in ("title", "note"):
        if key in data and not _text(data[key]):
            found.append(f"'{key}' must be non-empty text")
    if "version" in data and (not isinstance(data["version"], int) or isinstance(data["version"], bool)):
        found.append("'version' must be a whole number")
    for key in ("nodes", "edges"):
        value = data[key]
        if not isinstance(value, list) or not all(isinstance(x, dict) for x in value):
            found.append(f"'{key}' must be a list of objects")
    if found:
        return found
    found += [f"kind '{k}' has no shape in the renderer" for k in data["kinds"] if k not in _SHAPES]
    found += [f"relation '{r}' has no arrow in the renderer" for r in data["relations"] if r not in _ARROWS]
    for layer in data["layers"]:
        if not _LAYER_RE.fullmatch(layer):
            found.append(f"layer '{layer}' is not a plain lower-case word the diagrams can use as an id")
    return found


def problems(data: Any) -> list[str]:
    """Every way the data breaks its own contract; an empty list is a well-formed graph."""
    if not isinstance(data, dict):
        return ["the data is not a JSON object"]
    found = _shape_problems(data)
    if found:
        return found
    layers, kinds, relations = data["layers"], data["kinds"], data["relations"]
    ids: set[str] = set()
    labelled: set[tuple[str, str]] = set()
    for n in data["nodes"]:
        missing = [k for k in _NODE_KEYS if not _text(n.get(k))]
        if missing:
            found.append(f"node {n.get('id', '?')}: missing or not text: {', '.join(missing)}")
            continue
        nid = n["id"]
        if not _ID_RE.fullmatch(nid):
            found.append(f"node id '{nid}' is not lower-case kebab-case")
        if nid in ids:
            found.append(f"duplicate node id '{nid}'")
        ids.add(nid)
        if (n["layer"], n["label"]) in labelled:
            found.append(f"node {nid}: another node in layer '{n['layer']}' is also labelled '{n['label']}'")
        labelled.add((n["layer"], n["label"]))
        if n["kind"] not in kinds:
            found.append(f"node {nid}: unknown kind '{n['kind']}'")
        if n["layer"] not in layers:
            found.append(f"node {nid}: unknown layer '{n['layer']}'")
        for key in ("label", "summary"):
            if _break_problem(n[key]):
                found.append(f"node {nid}: {key} holds a pipe or a line break, which breaks the page's table")
        if any(c not in _SEEN_LETTERS for c in n["seen"]) or len(set(n["seen"])) != len(n["seen"]):
            found.append(f"node {nid}: seen '{n['seen']}' must be distinct letters of {_SEEN_LETTERS}")
    seen_edges: set[tuple[str, str, str]] = set()
    touched: set[str] = set()
    for e in data["edges"]:
        a, b, rel = e.get("from"), e.get("to"), e.get("relation")
        if not (_text(a) and _text(b) and _text(rel)):
            found.append(f"edge {a!r} -> {b!r}: from, to and relation must each be text")
            continue
        if a not in ids or b not in ids:
            found.append(f"edge {a} -> {b}: an endpoint is not a node")
            continue
        if a == b:
            found.append(f"edge {a} -> {b}: a node points at itself")
        if rel not in relations:
            found.append(f"edge {a} -> {b}: unknown relation '{rel}'")
        if (a, b, rel) in seen_edges:
            found.append(f"duplicate edge {a} -[{rel}]-> {b}")
        seen_edges.add((a, b, rel))
        touched.update((a, b))
    for orphan in sorted(ids - touched):
        found.append(f"node {orphan} has no edge")
    for rel in sorted(set(relations) - {e["relation"] for e in data["edges"] if _text(e.get("relation"))}):
        found.append(f"relation '{rel}' is declared and never used")
    used_layers = {n.get("layer") for n in data["nodes"]}
    for layer in layers:
        if layer not in used_layers:
            found.append(f"layer '{layer}' has no node")
    return found


def _mid(nid: str) -> str:
    """A node's Mermaid identifier: prefixed, so that no id (``end``, ``call``...) can be a Mermaid keyword, and
    with the hyphens of kebab-case turned into underscores (ids hold no underscore, so two ids cannot collide)."""
    return "n_" + nid.replace("-", "_")


def _lid(layer: str) -> str:
    """A layer's Mermaid identifier, prefixed for the same reason."""
    return "l_" + layer


def _label(text: str) -> str:
    """Text for a Mermaid label: quoted, with the characters Mermaid would read as markup written as its entity codes
    (``#35;`` for the hash itself, first, so that the others are not escaped twice)."""
    for char, entity in (("#", "#35;"), ('"', "#quot;"), ("<", "#lt;"), (">", "#gt;"), ("&", "#amp;")):
        text = text.replace(char, entity)
    return '"' + text + '"'


def _node_line(n: dict[str, Any], indent: str) -> str:
    left, right = _SHAPES[n["kind"]]
    return f"{indent}{_mid(n['id'])}{left}{_label(n['label'])}{right}"


def _flowchart(nodes: list[dict[str, Any]], edges: list[dict[str, Any]]) -> str:
    """One Mermaid flowchart: every node given, every edge among them."""
    keep = {n["id"] for n in nodes}
    lines = ["```mermaid", "flowchart LR"]
    lines.extend(_node_line(n, "  ") for n in nodes)
    for e in edges:
        if e["from"] in keep and e["to"] in keep:
            arrow = _ARROWS[e["relation"]]
            lines.append(f"  {_mid(e['from'])} {arrow}|{e['relation']}| {_mid(e['to'])}")
    for kind, style in _STYLE.items():
        ids = [_mid(n["id"]) for n in nodes if n["kind"] == kind]
        if ids:
            lines.append(f"  classDef {kind} {style}")
            lines.append(f"  class {','.join(ids)} {kind}")
    lines.append("```")
    return "\n".join(lines)


def render(data: dict[str, Any]) -> str:
    nodes, edges = data["nodes"], data["edges"]
    by_id = {n["id"]: n for n in nodes}
    layers = data["layers"]
    out = [
        HEADER,
        "# The AI-first framework graph",
        "",
        _STATUS_LINE,
        "",
        f"{len(nodes)} concepts in {len(layers)} layers, joined by {len(edges)} typed edges. {_SEEN_LINE}",
        "",
        "## Reading the diagrams",
        "",
        _READING,
        "",
        "| Relation | Meaning |",
        "| --- | --- |",
    ]
    counts = Counter(e["relation"] for e in edges)
    out.extend(f"| `{r}` | {m} ({counts[r]}) |" for r, m in data["relations"].items())
    out += ["", "## The layers", ""]
    cross = Counter((by_id[e["from"]]["layer"], by_id[e["to"]]["layer"]) for e in edges)
    lines = ["```mermaid", "flowchart TB"]
    for layer, title in layers.items():
        size = sum(1 for n in nodes if n["layer"] == layer)
        lines.append(f"  {_lid(layer)}[{_label(f'{layer} ({size}): {title}')}]")
    for (a, b), c in sorted(cross.items()):
        if a != b:
            lines.append(f"  {_lid(a)} -->|{c}| {_lid(b)}")
    lines.append("```")
    out += [
        "\n".join(lines),
        "",
        _BETWEEN,
        "",
    ]
    for layer, title in layers.items():
        members = [n for n in nodes if n["layer"] == layer]
        out += [f"## {layer.capitalize()}: {title}", ""]
        own = {m["id"] for m in members}
        touching = [e for e in edges if e["from"] in own or e["to"] in own]
        wanted = own | {e["from"] for e in touching} | {e["to"] for e in touching}
        out += [_flowchart([n for n in nodes if n["id"] in wanted], touching), ""]
        out += ["| Concept | Kind | Seen in | What it is |", "| --- | --- | --- | --- |"]
        for n in members:
            out.append(f"| **{n['label']}** (`{n['id']}`) | {n['kind']} | {n['seen']} | {n['summary']} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def diagram_problems(page: str) -> list[str]:
    """The Mermaid blocks of ``page`` that GitHub would refuse to draw: too many characters or too many edges."""
    found: list[str] = []
    for number, block in enumerate(
        re.findall(r"^```mermaid\n(.*?)^```$", page, flags=re.DOTALL | re.MULTILINE), start=1
    ):
        edges = sum(1 for line in block.splitlines() if re.search(r"(-->|-\.->|==>)", line))
        if len(block) > MAX_DIAGRAM_CHARS or edges > MAX_DIAGRAM_EDGES:
            found.append(
                f"diagram {number} has {len(block):,} characters and {edges} edges; GitHub draws at most 50,000 and "
                f"500, and this tool refuses {MAX_DIAGRAM_CHARS:,} and {MAX_DIAGRAM_EDGES}: split the layer"
            )
    return found


def findings(data: Any) -> list[str]:
    """Everything wrong with the graph before a page is written: its problems, else the diagrams GitHub cannot draw.
    ``--check`` and ``--write`` both report exactly these, with the same exit code."""
    return problems(data) or diagram_problems(render(data))


def check(root: Path = ROOT) -> tuple[list[str], str]:
    """The data's problems, and a diff of the committed page against a fresh render (empty when current)."""
    data = load(root / _KNOWLEDGE / DATA.name)
    found = findings(data)
    if found:
        return found, ""
    want = render(data)
    page = root / _KNOWLEDGE / PAGE.name
    try:
        have = (
            page.read_text(encoding="utf-8") if page.exists() else ""
        )  # universal newlines: a CRLF checkout is current
    except (OSError, ValueError) as e:
        raise GraphError(f"cannot read {page}: {type(e).__name__}: {e}") from e
    if have == want:
        return [], ""
    return [], "".join(difflib.unified_diff(have.splitlines(True), want.splitlines(True), "committed", "rendered", n=1))


def write(root: Path = ROOT) -> Path:
    data = load(root / _KNOWLEDGE / DATA.name)
    found = problems(data)
    if found:
        raise GraphError("the graph has problems: " + "; ".join(found))
    text = render(data)
    found = diagram_problems(text)
    if found:
        raise GraphError("the graph cannot be drawn: " + "; ".join(found))
    page = root / _KNOWLEDGE / PAGE.name
    temporary: Path | None = None
    try:  # written beside the page and moved over it, so a failed write cannot leave half a page
        # a file created exclusively under an unpredictable name: a link planted at a guessable name is never followed
        handle, name = tempfile.mkstemp(dir=page.parent, prefix=page.name + ".", suffix=".tmp")
        temporary = Path(name)
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        temporary.chmod(0o644)  # mkstemp makes it private; the page is a document everyone reads
        os.replace(temporary, page)
    except OSError as e:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
        raise GraphError(f"cannot write {page}: {type(e).__name__}: {e}") from e
    _LOGGER.info(f"wrote {page.name}: {len(data['nodes'])} nodes, {len(data['edges'])} edges")
    return page


def main(argv: list[str] | None = None, root: Path | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail when the graph is malformed or the page is stale")
    mode.add_argument("--write", action="store_true", help="regenerate the page from the data")
    parser.add_argument("--root", type=Path, default=None, help="the repository to read (default: this one)")
    parser.add_argument("-v", "--verbose", action="store_true", help="log what was read and written")
    args = parser.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):  # data with non-ASCII text must not crash the report
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(errors="backslashreplace")
    log_setup.configure(args.verbose)
    base = args.root if args.root is not None else (root if root is not None else ROOT)
    if not base.is_dir():
        print(f"graph check: cannot run: {base} is not a directory", file=sys.stderr)
        return 2
    try:
        if args.write:
            data = load(base / _KNOWLEDGE / DATA.name)
            found = findings(data)
            if found:  # the same findings, and the same exit code, as --check gives for this data
                for finding in found:
                    print(f"[graph] {finding}")
                return 1
            write(base)
            print(f"graph: wrote {PAGE.name}")
            return 0
        found, diff = check(base)
    except GraphError as e:
        print(f"graph check: cannot run: {e}", file=sys.stderr)
        return 2
    for finding in found:
        print(f"[graph] {finding}")
    if diff:
        sys.stdout.write(diff)
        print("[graph] the page is stale; run tools/render_framework_graph.py --write")
    if found or diff:
        return 1
    _LOGGER.info("checked the graph and compared its page with a fresh render")
    print("graph check: the graph is well formed and its page is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())

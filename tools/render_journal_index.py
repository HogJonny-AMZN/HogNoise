"""
Framework: render the journal's browsable index, and report who committed each session file.
Package: tools/render_journal_index

    uv run python tools/render_journal_index.py            # the same as --write: render <journal_dir>/INDEX.md
    uv run python tools/render_journal_index.py --print    # the same text on standard output; writes nothing
    uv run python tools/render_journal_index.py --authors  # non-gating: who committed each new-form file

``make journal`` runs the first form; the command is the interface and the target is a convenience.

The page lists the journal's new-form session files (``YYYY-MM-DD-<login>-HHMM.md``, each in its month folder
``YYYY-MM/``; one left at the top is listed too, and the docs check says where it belongs) as a table, newest first by
date, time and login, with each file's ``**Summary:**`` line as the link text, and points at the table in the journal's
``README.md`` for the older ``YYYY-MM-DD-session-NN.md`` files. It is **derived and not committed** (it is git-ignored,
and the docs check skips exactly that path), so a pull request that adds a session never edits a row and the page cannot
drift from the files.

``--authors`` prints one ``note:`` line for each new-form file whose adding commit was made by a roster person
other than the one in the file's name, or by an address nobody on the roster uses. It is evidence and never a gate:
it exits 0 whatever it finds, a squash merge or a rebase changes the author, and it says why it skipped (not a git work
tree, a shallow clone whose history is cut, git not installed, a configuration or journal directory it could not read)
instead of guessing. Only a ``--root`` that is not a directory is exit 2, as any bad argument is.

Exit codes: 0 done; 1 a new-form file has no usable ``**Summary:**`` (the page is still written, and the row says
``(no summary)``); 2 something could not be read or written (a file, the journal directory, the configuration, the
page; ``--authors`` reports those as a skip and exits 0). ``--root PATH`` points it at another repository (the
default is the one this file is in); ``-v`` logs what it read, decided and wrote to standard error.
"""

from __future__ import annotations

import argparse
import logging as _logging
import os
import posixpath
import subprocess
import sys
import tempfile
import unicodedata
import urllib.parse
from dataclasses import dataclass
from pathlib import Path

import check_docs as cd
import framework_config as fc

_MODULE_NAME = "tools.render_journal_index"
__version__ = "0.1.0"
__updated__ = "2026-10-28"
_LOGGER = _logging.getLogger(_MODULE_NAME)

ROOT = Path(__file__).resolve().parents[1]
PAGE_NAME = cd.DERIVED_INDEX
HEADER = "<!-- generated by tools/render_journal_index.py; not committed; do not edit -->"
NO_SUMMARY = "(no summary)"
_GIT_TIMEOUT = 30


class JournalError(Exception):
    """Something the tool could not read or write; ``main`` reports it and exits 2."""


@dataclass(frozen=True)
class Session:
    """One new-form session file."""

    name: str
    day: str  # YYYY-MM-DD
    hhmm: str  # HHMM, UTC
    login: str
    summary: str | None  # ``None``: the file has no usable summary
    rel: str  # the path from the journal directory: ``YYYY-MM/<name>`` in a month folder, ``<name>`` at the top

    @property
    def sort_key(self) -> tuple[str, str, str]:
        return (self.day, self.hhmm, self.login.lower())


# -------------------------------------------------------------------------
# reading the journal
def _configuration(base: Path) -> tuple[fc.DocsConfig, tuple[fc.Person, ...]]:
    path = base / "framework.toml"
    if not path.exists():
        _LOGGER.info(f"no framework.toml under {base}: the default journal directory applies, and there is no roster")
        return fc.DocsConfig(), ()
    try:
        config = fc.load_framework(path)
    except fc.ConfigError as e:
        raise JournalError(f"cannot read {path}: {e}") from e
    _LOGGER.info(f"read {path}: journal directory {config.docs.journal_dir}, {len(config.people)} on the roster")
    return config.docs, config.people


def _plain(text: str) -> str:
    """``text`` with every control, format and line- or paragraph-separator character turned into a space, so a summary
    cannot split a table row or reorder the text around it (U+2028, form feed, an escape, a bidirectional override)."""
    return "".join(" " if unicodedata.category(char) in ("Cc", "Cf", "Zl", "Zp") else char for char in text)


def _usable(summary: str | None) -> str | None:
    """The summary, made plain, if it is non-empty and within the limit, else ``None``."""
    return _plain(summary) if summary and len(summary) <= cd.SUMMARY_MAX else None


def _entries(directory: Path) -> list[str]:
    """The names in ``directory``, sorted; a directory that cannot be listed stops the run."""
    try:
        return sorted(entry.name for entry in directory.iterdir())
    except OSError as e:
        raise JournalError(f"cannot list the journal directory {directory}: {type(e).__name__}: {e}") from e


def read_sessions(directory: Path, *, summaries: bool = True) -> list[Session]:
    """The new-form session files in each month folder (``YYYY-MM/``) of ``directory`` and at its top, newest first.

    With ``summaries=False`` the files are not opened: the author report needs only their names, and one unreadable file
    must not stop a report that is never a gate.
    """
    places: list[tuple[str, str]] = [("", name) for name in _entries(directory)]
    for folder in [n for _, n in places if cd.MONTH_DIR_RE.fullmatch(n) and (directory / n).is_dir()]:
        places += [(folder, name) for name in _entries(directory / folder)]
    sessions: list[Session] = []
    for folder, name in places:
        if cd.journal_file_form(name) != "new":
            continue
        summary = None
        if summaries:
            try:
                text = (directory / folder / name).read_text(encoding="utf-8-sig")
            except (OSError, UnicodeDecodeError) as e:
                raise JournalError(f"cannot read {directory / folder / name}: {type(e).__name__}: {e}") from e
            summary = _usable(cd.session_summary(text))
        day, rest = name[:10], name[11:-3]
        login, _, hhmm = rest.rpartition("-")
        sessions.append(Session(name, day, hhmm, login, summary, posixpath.join(folder, name)))
    _LOGGER.info(f"read {len(places)} entries in {directory} and its month folders: {len(sessions)} session file(s)")
    return sorted(sessions, key=lambda s: s.sort_key, reverse=True)


# -------------------------------------------------------------------------
# the page
def _escape(text: str) -> str:
    """Text safe inside a table cell and a link's text: the characters markdown would read are backslash-escaped."""
    out = []
    for char in text:
        out.append("\\" + char if char in "\\|[]<>`" else char)
    return "".join(out)


def render(sessions: list[Session], older: str = "README.md") -> str:
    """The page text. ``older`` is the path from the page's directory to the file holding the older sessions' table
    (the configured ``journal_index``), which need not be a README beside the page."""
    target = urllib.parse.quote(older)
    label = _escape(posixpath.basename(older))
    lines = [
        HEADER,
        "",
        "# Journal index",
        "",
        "Newest first. Each link's text is the session's own summary. The older sessions, named",
        f"`YYYY-MM-DD-session-NN.md`, are in the table in [{label}]({target}).",
        "",
        "| Date | UTC | Author | Session |",
        "| --- | --- | --- | --- |",
    ]
    for s in sessions:
        text = _escape(s.summary) if s.summary else NO_SUMMARY
        lines.append(f"| {s.day} | {s.hhmm[:2]}:{s.hhmm[2:]} | @{s.login} | [{text}]({s.rel}) |")
    lines += ["", f"Older sessions: see the table in [{label}]({target}).", ""]
    return "\n".join(lines)


def write_page(page: Path, text: str) -> None:
    temporary: Path | None = None
    try:  # written beside the page and moved over it, so a failed write cannot leave half a page
        handle, name = tempfile.mkstemp(dir=page.parent, prefix=page.name + ".", suffix=".tmp")
        temporary = Path(name)
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        temporary.chmod(0o644)
        os.replace(temporary, page)
    except OSError as e:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
        raise JournalError(f"cannot write {page}: {type(e).__name__}: {e}") from e


# -------------------------------------------------------------------------
# the author report
def _git(base: Path, *args: str) -> subprocess.CompletedProcess[str]:
    """Run git in ``base``; output that is not UTF-8 (an author address in another encoding) is decoded with
    replacement characters instead of ending the run."""
    return subprocess.run(
        ["git", *args],
        cwd=base,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=_GIT_TIMEOUT,
        check=False,
    )


def _first_line(text: str) -> str:
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    return lines[0] if lines else "no message"


def authors_report(base: Path, directory_rel: str, sessions: list[Session], people: tuple[fc.Person, ...]) -> list[str]:
    """The lines of the author report: ``note:`` lines, or one line saying why nothing was compared.

    Git is asked once, for every commit that added a file under the journal directory, and the oldest adder of each
    session file is kept. A file renamed later is attributed to the commit that gave it its current name (git sees a
    rename as an add of the new name); that is a stated limit of the report.
    """
    if not people:
        return ["authors: no roster in framework.toml, so there is nothing to compare"]
    try:
        inside = _git(base, "rev-parse", "--is-inside-work-tree")
        if inside.returncode != 0:
            if "not a git repository" in inside.stderr.lower():
                return ["authors: skipped: not a git work tree"]
            return [f"authors: skipped: git failed: {_first_line(inside.stderr)}"]
        if inside.stdout.strip() != "true":
            return ["authors: skipped: not a git work tree"]
        if _git(base, "rev-parse", "--is-shallow-repository").stdout.strip() == "true":
            return ["authors: skipped: shallow clone: history is cut, so the adding commit is unknown"]
        if _git(base, "rev-parse", "--verify", "--quiet", "HEAD").returncode != 0:
            return ["authors: skipped: the repository has no commits yet"]
        wanted = {posixpath.join(directory_rel, s.rel) for s in sessions}
        log = _git(
            base,
            "log",
            "-z",  # names come back as they are: without -z git quotes a non-ASCII path, and nothing would match
            "--diff-filter=A",
            "--no-renames",
            "--relative",
            "--format=%x01%ae",
            "--name-only",
            "--",
            directory_rel,
        )
        if log.returncode != 0:
            return [f"authors: skipped: git log failed: {_first_line(log.stderr)}"]
        added_by: dict[str, str] = {}
        for chunk in log.stdout.split("\x01")[1:]:  # newest commit first, so a later chunk is an older adder and wins
            email, *names = chunk.split("\0")
            for name in names:
                name = name.removeprefix("\n")  # git ends the first commit line with a newline even under -z
                if name in wanted:
                    added_by[name] = email
        owner_of = {email.lower(): person.login for person in people for email in person.emails}
        notes: list[str] = []
        for s in sorted(sessions, key=lambda s: s.sort_key):
            rel = posixpath.join(directory_rel, s.rel)
            email = added_by.get(rel)
            if email is None:
                continue  # not committed yet: nothing to compare
            who = owner_of.get(email.lower())
            if who is None:
                notes.append(f"note: {rel} was added by {email}, which no roster person uses")
            elif who.lower() != s.login.lower():
                notes.append(f"note: {rel} was added by {email} ({who}), named {s.login}")
        _LOGGER.info(f"compared {len(sessions)} session file(s) with git history: {len(notes)} note(s)")
        return notes
    except FileNotFoundError:
        return ["authors: skipped: git not found"]
    except subprocess.TimeoutExpired:
        return [f"authors: skipped: git did not answer within {_GIT_TIMEOUT} seconds"]


def _emit(text: str) -> None:
    """Write ``text`` to standard output as UTF-8 bytes with the newlines it has, so ``--print`` is byte for byte what
    ``--write`` puts in the file, whatever the console's codec or newline translation."""
    buffer = getattr(sys.stdout, "buffer", None)
    if buffer is None:
        sys.stdout.write(text)
        return
    sys.stdout.flush()
    buffer.write(text.encode("utf-8"))
    buffer.flush()


# -------------------------------------------------------------------------
def main(argv: list[str] | None = None, root: Path | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="render the page (the default)")
    mode.add_argument("--print", action="store_true", dest="show", help="print the page text; write nothing")
    mode.add_argument("--authors", action="store_true", help="report who committed each file (non-gating)")
    parser.add_argument("--root", type=Path, default=None, help="the repository to read (default: this one)")
    parser.add_argument("-v", "--verbose", action="store_true", help="log what was read, decided and written")
    args = parser.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):  # summaries may hold non-ASCII text; reporting them must not crash
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(errors="backslashreplace")
    if args.verbose:
        _logging.basicConfig(level=_logging.INFO, format="%(message)s", stream=sys.stderr)
    base = args.root if args.root is not None else (root if root is not None else ROOT)
    if not base.is_dir():
        print(f"journal index: cannot run: {base} is not a directory", file=sys.stderr)
        return 2
    try:
        docs, people = _configuration(base)
        directory = base / docs.journal_dir
        if not directory.is_dir():
            raise JournalError(f"there is no journal directory {docs.journal_dir} under {base}")
        sessions = read_sessions(directory, summaries=not args.authors)
        if args.authors:
            for line in authors_report(base, docs.journal_dir, sessions, people):
                print(line)
            return 0
        text = render(sessions, posixpath.relpath(docs.journal_index, docs.journal_dir))
        missing = [s for s in sessions if s.summary is None]
        findings = sys.stderr if args.show else sys.stdout  # --print's standard output is the page and nothing else
        for s in missing:
            where = posixpath.join(docs.journal_dir, s.rel)
            print(
                f"[journal-index] {where}: no usable **Summary:** line (1 to {cd.SUMMARY_MAX} characters)",
                file=findings,
            )
        if args.show:
            _emit(text)
        else:
            write_page(directory / PAGE_NAME, text)
            _LOGGER.info(f"wrote {PAGE_NAME}: {len(sessions)} row(s), {len(missing)} without a summary")
            print(f"journal index: wrote {posixpath.join(docs.journal_dir, PAGE_NAME)} ({len(sessions)} sessions)")
        return 1 if missing else 0
    except JournalError as e:
        if args.authors:  # a report that is never a gate says what it could not read and exits 0
            print(f"authors: skipped: {e}")
            return 0
        print(f"journal index: cannot run: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())

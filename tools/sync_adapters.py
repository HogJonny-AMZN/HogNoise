"""
Framework: the harness layer: write each enabled harness's adapter and skills mirror, and check them.
Package: tools/sync_adapters

``AGENTS.md`` is the only context. A harness that does not read it natively gets an **adapter**: a generated file that
points to it (``CLAUDE.md``, ``.gemini/settings.json``, ``.github/copilot-instructions.md``). A harness that reads its
skills from a folder other than ``.agents/skills/`` gets a **skills mirror**: a copy of that tree. Both are generated
from the harnesses ``framework.toml`` enables, and ``--check`` fails on any that has text of its own or differs. Which
harness reads what, and where it was learned, is the compatibility matrix (``Docs/standards/compatibility-matrix.md``).

An adapter is exactly the generated pointer, except the Gemini settings file, which a project may share with its own
settings: it must name ``AGENTS.md`` as a context file, and ``--write`` adds that and keeps the rest. A mirror file is
compared byte for byte, except that a text file (by suffix) is compared with its line endings normalised, so a Windows
checkout is current. Symbolic links in the skills tree are refused.

The checks, each named in its finding (``[name] location: what is wrong``):

``adapter``    an enabled harness's adapter is missing or is not the generated pointer; or an adapter exists for a
               harness that is not enabled (delete it, or enable the harness)
``mirror``     the skills mirror of an enabled harness is missing a file, differs from ``.agents/skills/``, or holds
               a file the source does not; or a mirror exists for a harness that is not enabled
``probe``      a harness is enabled whose conformance probe has not passed: no single matrix row, no ``passed`` record
               with a real, not-future date and a name, or no matching passed entry in the probe log
``neutral``    a managed document names a harness outside the matrix and the probes document (the framework is
               harness-neutral; a name in prose is how an assumption gets in)
``corpus``     a check that could not see what it checks: no skills to mirror, no matrix, no managed document to read,
               a folder that could not be listed

Run standalone (exit code 0 clean or written, 1 findings, 2 the configuration or the arguments are unusable)::

    uv run python tools/sync_adapters.py (--check | --write) [-v] [--root PATH]

``--write`` refuses, with the ``probe`` finding, to generate for a harness whose probe has not passed. It never deletes
an adapter, only a stray file inside a mirror (the mirror is generated whole).
"""


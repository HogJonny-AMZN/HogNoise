_LOGGER = _logging.getLogger(_MODULE_NAME)

ROOT = Path(__file__).resolve().parent.parent

#: The one skills tree; every harness either reads it directly or gets a mirror of it.
SKILLS_SOURCE = ".agents/skills"
MATRIX = "Docs/standards/compatibility-matrix.md"
PROBES = "Docs/standards/harness-probes.md"
MATRIX_HEADING = "## The matrix"
LOG_HEADING = "## Probe log"

#: The files that may name a harness: the matrix and the probes document are where harnesses are described.
NEUTRAL_EXEMPT = (MATRIX, PROBES)

_MARKER = "generated by tools/sync_adapters.py from framework.toml; do not edit"
CLAUDE_MD = f"<!-- {_MARKER}. The instructions are in AGENTS.md. -->\n@AGENTS.md\n"
COPILOT_MD = (
    f"<!-- {_MARKER}. -->\n"
    "The instructions for any coding agent working in this repository are in [AGENTS.md](../AGENTS.md). Read it first; "
    "it points to everything else.\n"
)
GEMINI_JSON = '{\n  "context": {\n    "fileName": ["AGENTS.md"]\n  }\n}\n'


@dataclass(frozen=True)
class Harness:
    """One harness: what it is called, the adapter it needs (None when it reads ``AGENTS.md`` natively), the text of
    that adapter, whether the adapter is a settings file shared with the project (checked by meaning, not by text), and
    the folder its skills are mirrored into (None when it reads ``.agents/skills/`` directly)."""

    key: str
    name: str
    adapter: str | None
    content: str | None
    mirror: str | None
    shared: bool = False


#: Every harness the framework knows, in ``fc.HARNESSES`` order. A test holds the two lists to each other.
HARNESS_TABLE: tuple[Harness, ...] = (
    Harness("claude", "Claude Code", "CLAUDE.md", CLAUDE_MD, ".claude/skills"),
    Harness("gemini", "Gemini CLI", ".gemini/settings.json", GEMINI_JSON, None, shared=True),
    Harness("copilot", "GitHub Copilot", ".github/copilot-instructions.md", COPILOT_MD, None),
    Harness("codex", "Codex", None, None, None),
    Harness("cursor", "Cursor", None, None, None),
)

#: Names that mark a document as naming a harness, matched as whole words without regard to case. ``cursor`` is an
#: ordinary word (a text cursor), so Cursor is matched by its product phrases instead.
NEUTRAL_WORDS = (
    "claude",
    "anthropic",
    "gemini",
    "antigravity",
    "copilot",
    "codex",
    "openai",
    "chatgpt",
    "gpt",
    "windsurf",
    "codeium",
    "aider",
    "cline",
    "kiro",
)
NEUTRAL_PHRASES = (r"cursor\s+(?:ide|agent|editor|cli)", r"\.cursor(?:rules)?")
_NAME_RE = re.compile(
    r"(?<![A-Za-z0-9_])(" + "|".join((*NEUTRAL_WORDS, *NEUTRAL_PHRASES)) + r")(?![A-Za-z0-9_])", re.IGNORECASE
)
#: Folders the ``neutral`` check never enters: other checkouts, environments and the initialiser's run records.
SKIPPED_DIRS = frozenset({".git", ".venv", "node_modules", "__pycache__", "logs"})
#: What is read for the ``neutral`` check: the managed files with these suffixes (compared in lower case).
NEUTRAL_SUFFIXES = (".md", ".json")
#: Files compared with their line endings normalised; any other file in a mirror is compared byte for byte.
TEXT_SUFFIXES = (".md", ".json", ".txt", ".toml", ".yml", ".yaml", ".py", ".sh")

_PROBE_RE = re.compile(r"^passed (\d{4}-\d{2}-\d{2}) by (\S.*)$")
_KEY_RE = re.compile(r"^`([a-z]+)`$")


class AdapterError(Exception):
    """The configuration cannot be read, or a file cannot be read or written."""


@dataclass(frozen=True)
class Finding:
    """One inconsistency: the check that found it, where, and what is wrong."""

    check: str
    location: str
    detail: str

    def __str__(self) -> str:
        return f"[{self.check}] {self.location}: {self.detail}"


# -------------------------------------------------------------------------
# reading and writing
def _bytes(path: Path, *, text: bool) -> bytes | None:
    """A file's bytes (line endings normalised when ``text``), None when it is not there. Raises ``AdapterError``."""
    try:
        data = path.read_bytes()
    except FileNotFoundError:
        return None
    except OSError as e:
        raise AdapterError(f"cannot read {path}: {type(e).__name__}: {e}") from e
    return data.replace(b"\r\n", b"\n") if text else data


def _text(path: Path) -> str | None:
    """A document's text (a BOM and CRLF tolerated), None when it is not there. Raises ``AdapterError``."""
    data = _bytes(path, text=True)
    if data is None:
        return None
    try:
        return data.decode("utf-8-sig")
    except UnicodeDecodeError as e:
        raise AdapterError(f"cannot read {path}: {type(e).__name__}: {e}") from e


def _is_text(rel: str) -> bool:
    return rel.lower().endswith(TEXT_SUFFIXES)


def _write_atomic(path: Path, data: bytes, *, executable: bool = False) -> None:
    """Write ``data`` beside ``path`` under an unpredictable name and move it over, so no half file is left."""
    temporary: Path | None = None
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        handle, name = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
        temporary = Path(name)
        with os.fdopen(handle, "wb") as stream:
            stream.write(data)
        temporary.chmod(0o755 if executable else 0o644)
        os.replace(temporary, path)
    except OSError as e:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
        raise AdapterError(f"cannot write {path}: {type(e).__name__}: {e}") from e


def _tree(base: Path) -> dict[str, tuple[bytes, bool]]:
    """``{relative path: (bytes, executable)}`` for every file under ``base``; empty when it is not there.

    :raises AdapterError: a file cannot be read, or a symbolic link is in the tree (it could copy a file from anywhere).
    """
    tree: dict[str, tuple[bytes, bool]] = {}
    if base.is_symlink():  # the root too: through a link, a write or a delete would land outside the repository
        raise AdapterError(f"{base} is a symbolic link; a skills tree is a real folder")
    if not base.is_dir():
        return tree
    for path in sorted(base.rglob("*")):
        if path.is_symlink():
            raise AdapterError(f"{path} is a symbolic link; a skills tree holds real files only")
        if path.is_file():
            rel = path.relative_to(base).as_posix()
            data = _bytes(path, text=_is_text(rel))
            assert data is not None
            tree[rel] = (data, os.name != "nt" and bool(path.stat().st_mode & 0o111))
    return tree


# -------------------------------------------------------------------------
# the compatibility matrix
def _section(text: str, heading: str) -> list[str]:
    """The lines under ``heading`` up to the next ``## `` heading; empty when there is no such heading."""
    lines = text.splitlines()
    if heading not in lines:
        return []
    rest = lines[lines.index(heading) + 1 :]
    end = next((i for i, line in enumerate(rest) if line.startswith("## ")), len(rest))
    return rest[:end]


def _rows(lines: list[str]) -> list[list[str]]:
    return [[c.strip() for c in line.strip().strip("|").split("|")] for line in lines if line.strip().startswith("|")]


def matrix_rows(root: Path) -> list[tuple[str, str]]:
    """``(harness key, probe cell)`` for each row of the matrix table (and only that table), in order."""
    text = _text(root / MATRIX)
    rows = []
    for cells in _rows(_section(text or "", MATRIX_HEADING)):
        if len(cells) >= 2 and (key := _KEY_RE.match(cells[1])):
            rows.append((key.group(1), cells[-1]))
    return rows


def probe_log(root: Path) -> list[tuple[str, str, str]]:
    """``(date, harness key, result)`` for each row of the probe log table, in order."""
    text = _text(root / MATRIX)
    entries = []
    for cells in _rows(_section(text or "", LOG_HEADING)):
        if len(cells) >= 4 and (key := _KEY_RE.match(cells[1])):
            entries.append((cells[0], key.group(1), cells[3]))
    return entries


def _passed(cell: str, today: datetime.date) -> tuple[str, str] | str:
    """``(date, who)`` when ``cell`` records a pass, else a reason it does not."""
    match = _PROBE_RE.match(cell)
    if not match:
        return "has not passed (record 'passed YYYY-MM-DD by <name>')"
    try:
        day = datetime.date.fromisoformat(match.group(1))
    except ValueError:
        return f"records a pass on {match.group(1)!r}, which is not a day"
    if day > today:
        return f"records a pass dated {day}, which is in the future"
    return match.group(1), match.group(2).strip()


def probe_status(root: Path, today: datetime.date | None = None) -> dict[str, tuple[str, str] | None]:
    """``{harness key: (date, who) when its probe passed, else None}``; the last row wins when a key repeats (a
    repeat is reported by ``check_probes``)."""
    today = today or datetime.datetime.now(datetime.UTC).date()  # records carry the UTC day (framework ledger 38)
    return {key: (r if not isinstance(r := _passed(cell, today), str) else None) for key, cell in matrix_rows(root)}


# -------------------------------------------------------------------------
# the checks
def _gemini_problem(data: bytes) -> str | None:
    """Why a Gemini settings file does not name ``AGENTS.md`` as a context file, or None when it does."""
    try:
        settings = json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as e:  # a byte order mark is refused too: the CLI may not parse it
        return f"is not valid JSON ({type(e).__name__}: {e})"
    context = settings.get("context") if isinstance(settings, dict) else None
    names = context.get("fileName") if isinstance(context, dict) else None
    if isinstance(names, str):
        names = [names]
    if not isinstance(names, list) or "AGENTS.md" not in names:
        return "does not name AGENTS.md as a context file (context.fileName)"
    return None


def _adapter_problem(harness: Harness, data: bytes) -> str | None:
    if harness.shared:
        return _gemini_problem(data)
    assert harness.content is not None
    return (
        None
        if data == harness.content.encode("utf-8")
        else "is not the generated pointer (an adapter holds no text of its own)"
    )


def check_adapters(root: Path, enabled: tuple[str, ...]) -> list[Finding]:
    """The adapter of each enabled harness is present and correct; none exists for a harness that is not enabled."""
    found: list[Finding] = []
    for harness in HARNESS_TABLE:
        if harness.adapter is None or harness.content is None:
            continue
        have = _bytes(root / harness.adapter, text=True)
        if harness.key in enabled:
            if have is None:
                found.append(Finding("adapter", harness.adapter, f"missing for the enabled harness {harness.key}"))
            elif problem := _adapter_problem(harness, have):
                found.append(Finding("adapter", harness.adapter, problem))
        elif have is not None and (not harness.shared or _adapter_problem(harness, have) is None):
            # any file at a dedicated adapter's path; the shared settings file only if it points here
            found.append(
                Finding(
                    "adapter",
                    harness.adapter,
                    f"belongs to {harness.key}, which is not enabled in framework.toml: "
                    f"delete it, or enable {harness.key}",
                )
            )
        _LOGGER.info(f"adapter {harness.adapter}: {'enabled' if harness.key in enabled else 'not enabled'}")
    return found


def check_mirrors(root: Path, enabled: tuple[str, ...]) -> list[Finding]:
    """The skills mirror of each enabled harness equals ``.agents/skills/``; none exists for a harness that is not."""
    found: list[Finding] = []
    source: dict[str, tuple[bytes, bool]] | None = None  # read only when a mirror is enabled
    for harness in HARNESS_TABLE:
        if harness.mirror is None:
            continue
        have = _tree(root / harness.mirror)
        if harness.key not in enabled:
            if have:
                found.append(
                    Finding(
                        "mirror",
                        harness.mirror,
                        f"is a skills mirror for {harness.key}, which is not enabled: "
                        f"delete it, or enable {harness.key}",
                    )
                )
            continue
        if source is None:
            source = _tree(root / SKILLS_SOURCE)
        if not source:
            found.append(Finding("corpus", SKILLS_SOURCE, f"has no skills to mirror into {harness.mirror}"))
            continue
        for rel in sorted(source):
            if rel not in have:
                found.append(Finding("mirror", f"{harness.mirror}/{rel}", "is missing from the mirror"))
            elif have[rel] != source[rel]:
                found.append(Finding("mirror", f"{harness.mirror}/{rel}", f"differs from {SKILLS_SOURCE}/{rel}"))
        for rel in sorted(set(have) - set(source)):
            found.append(Finding("mirror", f"{harness.mirror}/{rel}", f"is not in {SKILLS_SOURCE} (a stray file)"))
        _LOGGER.info(f"mirror {harness.mirror}: {len(have)} file(s) against {len(source)} in the source")
    return found


def check_probes(root: Path, enabled: tuple[str, ...], today: datetime.date | None = None) -> list[Finding]:
    """Each enabled harness has exactly one matrix row recording a real, dated, signed pass that the probe log backs."""
    if _text(root / MATRIX) is None:  # first: with nothing enabled the matrix is still a required document
        return [Finding("corpus", MATRIX, "is missing, so no probe can be shown to have passed")]
    if not enabled:
        return []
    today = today or datetime.datetime.now(datetime.UTC).date()  # records carry the UTC day (framework ledger 38)
    rows = matrix_rows(root)
    log = probe_log(root)
    found: list[Finding] = []
    for key in enabled:
        mine = [cell for k, cell in rows if k == key]
        if not mine:
            found.append(Finding("probe", MATRIX, f"has no row for the enabled harness {key}"))
            continue
        if len(mine) > 1:
            found.append(Finding("probe", MATRIX, f"has {len(mine)} rows for {key}; there must be one"))
            continue
        result = _passed(mine[0], today)
        if isinstance(result, str):
            found.append(Finding("probe", MATRIX, f"{key} is enabled but its probe {result}"))
        elif not any(d == result[0] and k == key and r.lower().startswith("passed") for d, k, r in log):
            found.append(
                Finding(
                    "probe", MATRIX, f"{key} passed on {result[0]} but the probe log has no passed entry for that day"
                )
            )
    return found


def _source_of_mirror(rel: str, mirrors: dict[str, Harness]) -> str | None:
    """The ``.agents/skills`` path that ``rel`` is a mirror copy of, or ``None`` when it is not in a mirror."""
    for folder in mirrors:
        if rel.startswith(folder + "/"):
            return f"{SKILLS_SOURCE}/{rel[len(folder) + 1 :]}"
    return None


def _is_skill_extension(rel: str, mirrors: dict[str, Harness]) -> bool:
    """``rel`` is a skill's extension, ``project.md`` directly in a skill's folder under ``.agents/skills``, or its
    copy in a harness's mirror: the project's own text, which the manifest's ``.agents/skills/*`` rule cannot tell from
    the skill (a manifest rule that matches no payload file is refused, and an extension is never shipped)."""
    source = _source_of_mirror(rel, mirrors) or rel
    parts = source.split("/")
    return len(parts) == 4 and parts[:2] == SKILLS_SOURCE.split("/") and parts[3] == "project.md"


def check_neutral(root: Path, overridden: frozenset[str] = frozenset()) -> list[Finding]:
    """Managed documents may not name a harness outside ``NEUTRAL_EXEMPT``.

    A file listed in ``overridden`` (``[[overrides]]`` in ``framework.toml``) is the project's own text, so the
    framework's neutrality is not asked of it; it is still listed as an override on every sync check. A skill's
    extension (``project.md`` directly in its folder) is the project's text too, and is skipped. A skills mirror
    file inherits the exemption of the ``.agents/skills`` file it is a copy of (``check_mirrors`` still holds it equal
    to its source, so the exemption cannot hide a divergent copy). The corpus guard counts an overridden document that
    exists, so a repository that overrides every document is not reported as having none."""
    mirrors = {h.mirror: h for h in HARNESS_TABLE if h.mirror}
    manifest = root / init.MANIFEST_NAME
    if not manifest.is_file():
        return [
            Finding("corpus", init.MANIFEST_NAME, "is missing, so the managed documents cannot be told from the rest")
        ]
    try:
        rules = init.load_manifest(manifest)
    except init.ManifestError as e:
        raise AdapterError(str(e)) from e
    found: list[Finding] = []
    scanned = 0
    excused = 0
    unlistable: list[OSError] = []
    for dirpath, dirnames, filenames in os.walk(root, onerror=unlistable.append):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIPPED_DIRS)  # pruned: an environment is never entered
        for name in sorted(filenames):
            path = Path(dirpath) / name
            rel = path.relative_to(root).as_posix()
            if not rel.lower().endswith(NEUTRAL_SUFFIXES) or rel in NEUTRAL_EXEMPT:
                continue
            if _is_skill_extension(rel, mirrors):
                continue  # a skill's extension is the project's text; the mirror check holds its copy equal
            rule = init.classify(rules, rel)
            if rule is None or rule.kind != "managed":
                continue
            if rel in overridden or _source_of_mirror(rel, mirrors) in overridden:
                excused += 1
                continue
            text = _text(path)
            if text is None:
                continue
            scanned += 1
            for number, line in enumerate(text.splitlines(), start=1):
                hit = _NAME_RE.search(line)
                if hit:
                    found.append(
                        Finding(
                            "neutral", f"{rel}:{number}", f"names a harness ({hit.group(1)!r}); only the matrix may"
                        )
                    )
    for error in unlistable:  # a folder that cannot be listed is a folder that was not checked
        where = Path(error.filename).relative_to(root).as_posix() if error.filename else root.as_posix()
        found.append(
            Finding("corpus", where, f"cannot be listed, so it was not checked: {type(error).__name__}: {error}")
        )
    if not scanned and not excused:
        found.append(Finding("corpus", root.as_posix(), "has no managed document to check for harness names"))
    _LOGGER.info(f"neutral check read {scanned} managed document(s), {excused} excused by an override")
    return found


def run_checks(root: Path) -> list[Finding]:
    """Every finding, in a stable order. Raises ``AdapterError`` (and ``fc.ConfigError``) when it cannot run."""
    config = fc.load_framework(root / "framework.toml")
    enabled = config.harnesses
    _LOGGER.info(f"enabled harnesses: {', '.join(enabled) or 'none'}")
    return [
        *check_probes(root, enabled),
        *check_adapters(root, enabled),
        *check_mirrors(root, enabled),
        *check_neutral(root, frozenset(o.target for o in config.overrides)),
    ]


# -------------------------------------------------------------------------
# writing
def _merged_gemini(existing: bytes) -> bytes:
    """The settings file with ``AGENTS.md`` added to ``context.fileName``, every other setting kept."""
    try:
        settings = json.loads(existing.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as e:
        raise AdapterError(
            f".gemini/settings.json cannot be read, so it is not overwritten ({type(e).__name__}: {e})"
        ) from e
    if not isinstance(settings, dict) or not isinstance(settings.get("context", {}), dict):
        raise AdapterError(".gemini/settings.json is not an object with an object 'context', so it is not overwritten")
    context = settings.setdefault("context", {})
    names = context.get("fileName", [])
    names = [names] if isinstance(names, str) else names
    if not isinstance(names, list) or not all(isinstance(n, str) for n in names):
        raise AdapterError(
            ".gemini/settings.json: context.fileName is not a string or an array of strings, so it is not changed"
        )
    if "AGENTS.md" not in names:
        context["fileName"] = [*names, "AGENTS.md"]
    return (json.dumps(settings, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def write_all(root: Path) -> list[str]:
    """Generate the adapters and mirrors of the enabled harnesses. Returns what was written; refuses (``AdapterError``)
    when an enabled harness's probe has not passed."""
    enabled = fc.load_framework(root / "framework.toml").harnesses
    unproven = check_probes(root, enabled)
    if unproven:
        raise AdapterError("; ".join(str(f) for f in unproven))
    written: list[str] = []
    source: dict[str, tuple[bytes, bool]] | None = None
    for harness in HARNESS_TABLE:
        if harness.key not in enabled:
            continue
        if harness.adapter and harness.content is not None:
            have = _bytes(root / harness.adapter, text=True)
            if have is None:
                _write_atomic(root / harness.adapter, harness.content.encode("utf-8"))
                written.append(harness.adapter)
            elif _adapter_problem(harness, have):
                data = _merged_gemini(have) if harness.shared else harness.content.encode("utf-8")
                _write_atomic(root / harness.adapter, data)
                written.append(harness.adapter)
        if harness.mirror:
            if source is None:
                source = _tree(root / SKILLS_SOURCE)
            if not source:
                raise AdapterError(f"{SKILLS_SOURCE} has no skills to mirror into {harness.mirror}")
            have_tree = _tree(root / harness.mirror)
            for rel, (data, executable) in source.items():
                if have_tree.get(rel) != (data, executable):
                    _write_atomic(root / harness.mirror / rel, data, executable=executable)
                    written.append(f"{harness.mirror}/{rel}")
            for rel in sorted(set(have_tree) - set(source)):  # the mirror is generated whole, so a stray file goes
                try:
                    (root / harness.mirror / rel).unlink()
                except OSError as e:
                    raise AdapterError(f"cannot remove {root / harness.mirror / rel}: {type(e).__name__}: {e}") from e
                written.append(f"{harness.mirror}/{rel} (removed: not in {SKILLS_SOURCE})")
    _LOGGER.info(f"wrote {len(written)} file(s)")
    return written


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):  # a finding naming a non-ASCII file must not crash the report
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(errors="backslashreplace")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail when an adapter or mirror is wrong, or a name leaks")
    mode.add_argument("--write", action="store_true", help="generate the adapters and mirrors of the enabled harnesses")
    parser.add_argument("--root", type=Path, default=ROOT, help="the repository (default: this one)")
    parser.add_argument("-v", "--verbose", action="store_true", help="log what was read and written to standard error")
    args = parser.parse_args(argv)
    log_setup.configure(args.verbose)
    root = args.root.resolve()
    if not root.is_dir():
        print(f"adapters: cannot run: {root} is not a directory", file=sys.stderr)
        return 2
    try:
        if args.write:
            unproven = check_probes(root, fc.load_framework(root / "framework.toml").harnesses)
            if unproven:  # the same findings, and the same exit code, as --check gives for this configuration
                for finding in unproven:
                    print(finding)
                return 1
            written = write_all(root)
            for item in written:
                print(f"wrote {item}")
            print(f"adapters: wrote {len(written)} file(s)")
            return 0
        found = run_checks(root)
    except (AdapterError, fc.ConfigError) as e:
        print(f"adapters: cannot run: {e}", file=sys.stderr)
        return 2
    for finding in found:
        print(finding)
    if found:
        print(f"adapters: {len(found)} finding(s)")
        return 1
    print("adapters: clean")
    return 0


if __name__ == "__main__":
    sys.exit(main())

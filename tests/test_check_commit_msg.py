"""
Framework: tests for tools/check_commit_msg.py (no AI attribution; an accepted sign-off, the owner's or a roster
person's, when the project requires one).
Package: tests/test_check_commit_msg
"""

from __future__ import annotations

import subprocess
import sys
from dataclasses import replace
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import check_commit_msg as ccm  # noqa: E402
import framework_config as fc  # noqa: E402

SIGNOFF = "Signed-off-by: Ada Example <ada@example.org>"


def _project(signoff: bool = True) -> fc.ProjectConfig:
    return fc.ProjectConfig(
        name="Example",
        slug="example",
        owner=fc.Owner(name="Ada Example", email="ada@example.org"),
        default_branch="main",
        signoff=signoff,
        hygiene=(),
    )


def _root(tmp_path: Path, signoff: bool = True) -> Path:
    (tmp_path / "project.json").write_text(fc.dump_project(_project(signoff)), encoding="utf-8")
    return tmp_path


def _message(tmp_path: Path, text: str) -> Path:
    path = tmp_path / "COMMIT_EDITMSG"
    path.write_text(text, encoding="utf-8")
    return path


# ---- accepted
def test_a_signed_message_with_no_attribution_is_accepted() -> None:
    assert ccm.check_message(f"Add the thing\n\nWhy it matters.\n\n{SIGNOFF}\n", _project()) == []


def test_a_human_co_author_is_not_an_ai_attribution() -> None:
    message = f"Pair work\n\nCo-authored-by: Grace Hopper <grace@example.org>\n{SIGNOFF}\n"
    assert ccm.check_message(message, _project()) == []


def test_prose_that_says_generated_is_not_a_footer_naming_an_ai() -> None:
    message = f"Regenerate the page\n\nGenerated with the project's own script.\n\n{SIGNOFF}\n"
    assert ccm.check_message(message, _project()) == []


def test_a_project_that_does_not_require_a_signoff_accepts_a_message_without_one() -> None:
    assert ccm.check_message("Add the thing\n", _project(signoff=False)) == []


# ---- rejected: attribution
@pytest.mark.parametrize(
    "trailer",
    [
        "Co-Authored-By: Claude <noreply@anthropic.com>",
        "Co-authored-by: Claude Opus <claude@example.org>",
        "co-authored-by: GitHub Copilot <copilot@github.com>",
        "Co-authored-by: Gemini <gemini@example.org>",
        "Co-authored-by: ChatGPT <chatgpt@openai.com>",
        "Co-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>",
        "  Co-Authored-By : Cursor Agent <cursoragent@cursor.com>",
    ],
)
def test_an_ai_co_author_trailer_is_rejected(trailer: str) -> None:
    found = ccm.check_message(f"Add the thing\n\n{trailer}\n{SIGNOFF}\n", _project())
    assert len(found) == 1 and "AI attribution trailer" in found[0], found


@pytest.mark.parametrize(
    "footer",
    [
        "Generated with Claude Code",
        "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
        "Generated by Copilot",
    ],
)
def test_a_generated_with_footer_naming_an_ai_is_rejected(footer: str) -> None:
    found = ccm.check_message(f"Add the thing\n\n{footer}\n\n{SIGNOFF}\n", _project())
    assert len(found) == 1 and "'Generated with/by' footer" in found[0], found


@pytest.mark.parametrize(
    "trailer",
    [
        "Assisted-by: Claude:opus",
        "assisted-by: GitHub Copilot",
        "Generated-by: Claude Code",
        "Co-authored-by: Aider <noreply@aider.chat>",
        "Co-authored-by: Windsurf <cascade@windsurf.com>",
    ],
)
def test_the_other_attribution_trailers_and_tools_are_rejected_too(trailer: str) -> None:
    found = ccm.check_message(f"Add the thing\n\n{trailer}\n{SIGNOFF}\n", _project())
    assert len(found) == 1 and "not allowed" in found[0], found


@pytest.mark.parametrize(
    "comment",
    ["# Co-Authored-By: Claude <noreply@anthropic.com>", "# Generated with Claude Code", "#🤖 Generated by Copilot"],
)
def test_a_commented_out_attribution_is_still_rejected(comment: str) -> None:
    """Git keeps a ``#`` line when the message is given with ``-m``, so a commented-out attribution would ship."""
    found = ccm.check_message(f"Add the thing\n\n{comment}\n{SIGNOFF}\n", _project())
    assert len(found) == 1 and "not allowed" in found[0], found


def test_a_person_who_shares_a_tools_name_is_rejected_and_the_remedy_is_the_body() -> None:
    """A known cost of a name list, pinned so that it is a decision and not a surprise (see AI_NAMES)."""
    message = f"Pair work\n\nCo-authored-by: Claude Monet <monet@example.org>\n{SIGNOFF}\n"
    assert len(ccm.check_message(message, _project())) == 1
    assert ccm.check_message(f"Pair work with Claude Monet\n\n{SIGNOFF}\n", _project()) == []



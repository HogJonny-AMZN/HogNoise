# ---- the command line
def test_main_accepts_rejects_and_names_the_reasons(tmp_path: Path, capsys) -> None:
    root = _root(tmp_path)
    assert ccm.main(["--root", str(root), str(_message(tmp_path, f"Add\n\n{SIGNOFF}\n"))]) == 0
    assert capsys.readouterr().err == ""
    assert ccm.main(["--root", str(root), str(_message(tmp_path, "Add\n"))]) == 1
    err = capsys.readouterr().err
    assert "[commit-msg] the sign-off is missing" in err and "the commit was not made" in err


def test_main_is_unusable_without_a_message_or_a_project(tmp_path: Path, capsys) -> None:
    assert ccm.main(["--root", str(tmp_path), str(_message(tmp_path, "x\n"))]) == 2  # no project.json
    assert "cannot run" in capsys.readouterr().err
    assert ccm.main(["--root", str(_root(tmp_path)), str(tmp_path / "missing")]) == 2


def test_verbose_is_the_only_thing_that_makes_it_log(tmp_path: Path) -> None:
    """In a process of its own: logging is configured once per process."""
    root = _root(tmp_path)
    base = [sys.executable, str(ROOT / "tools" / "check_commit_msg.py"), "--root", str(root)]
    message = str(_message(tmp_path, f"Add\n\n{SIGNOFF}\n"))
    quiet = subprocess.run([*base, message], capture_output=True, text=True, check=False)
    loud = subprocess.run([*base, "-v", message], capture_output=True, text=True, check=False)
    assert quiet.returncode == loud.returncode == 0
    assert quiet.stderr == "" and "signoff required: True" in loud.stderr


def test_the_script_runs_as_the_hook_runs_it(tmp_path: Path) -> None:
    root = _root(tmp_path)
    script = ROOT / "tools" / "check_commit_msg.py"
    bad = _message(tmp_path, "Add\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n")
    ran = subprocess.run(
        [sys.executable, str(script), "--root", str(root), str(bad)], capture_output=True, text=True, check=False
    )
    assert ran.returncode == 1 and "AI attribution" in ran.stderr and "the sign-off is missing" in ran.stderr


# ---- the roster: a person on it signs as themselves
MOON = fc.Person(
    login="PlanarKnight", name="Moon Mulligan", role="contributor", emails=("moon@example.org", "m2@example.org")
)
NO_MAIL = fc.Person(login="nomail", name="No Mail", role="contributor", emails=())
OWNER_ROW = fc.Person(login="ada", name="Ada Example", role="owner", emails=("ada@example.org",))
MOON_SIGNOFF = "Signed-off-by: Moon Mulligan <moon@example.org>"


def _roster_root(tmp_path: Path, *people: fc.Person) -> Path:
    """A root with ``project.json`` and a ``framework.toml`` carrying ``people`` (the payload's own, re-rostered)."""
    root = _root(tmp_path)
    base = fc.load_framework(ROOT / "framework.toml")
    (root / "framework.toml").write_text(fc.dump_framework(replace(base, people=people)), encoding="utf-8")
    return root


def test_the_owner_signs_with_no_roster_as_before() -> None:
    assert ccm.check_message(f"Add\n\n{SIGNOFF}\n", _project(), ()) == []


@pytest.mark.parametrize("email", ["moon@example.org", "m2@example.org", "MOON@Example.ORG"])
def test_a_roster_person_signs_with_their_name_and_any_of_their_addresses(email: str) -> None:
    assert ccm.check_message(f"Add\n\nSigned-off-by: Moon Mulligan <{email}>\n", _project(), (MOON,)) == []


def test_a_roster_address_with_another_name_is_rejected_and_the_roster_identity_is_named() -> None:
    (found,) = ccm.check_message("Add\n\nSigned-off-by: PlanarKnight <moon@example.org>\n", _project(), (MOON,))
    assert "not an accepted identity" in found and "Moon Mulligan <moon@example.org>" in found


def test_a_roster_name_with_an_address_not_on_the_row_is_rejected() -> None:
    assert len(ccm.check_message("Add\n\nSigned-off-by: Moon Mulligan <other@example.org>\n", _project(), (MOON,))) == 1


@pytest.mark.parametrize("email", ["nomail@example.org", "ada@example.org", ""])
def test_a_roster_person_with_no_address_cannot_sign(email: str) -> None:
    assert len(ccm.check_message(f"Add\n\nSigned-off-by: No Mail <{email}>\n", _project(), (NO_MAIL,))) == 1


def test_a_stranger_is_rejected_and_every_accepted_identity_is_listed_and_no_other() -> None:
    (found,) = ccm.check_message("Add\n\nSigned-off-by: Someone Else <else@example.org>\n", _project(), (MOON, NO_MAIL))
    listed = [line.strip() for line in found.splitlines() if line.strip().startswith("Signed-off-by:")]
    assert listed == [
        "Signed-off-by: Ada Example <ada@example.org>    (the owner, project.json)",
        "Signed-off-by: Moon Mulligan <moon@example.org>    (the roster, framework.toml: @PlanarKnight)",
        "Signed-off-by: Moon Mulligan <m2@example.org>    (the roster, framework.toml: @PlanarKnight)",
    ]


def test_accepted_identities_are_the_owner_then_each_roster_address() -> None:
    assert [(n, e) for n, e, _ in ccm.accepted_identities(_project(), (NO_MAIL, MOON))] == [
        ("Ada Example", "ada@example.org"),
        ("Moon Mulligan", "moon@example.org"),
        ("Moon Mulligan", "m2@example.org"),
    ]


def test_a_project_without_a_signoff_accepts_a_roster_person_without_one() -> None:
    assert ccm.check_message("Add\n", _project(signoff=False), (MOON,)) == []


def test_a_merge_message_needs_no_signoff_with_a_roster_either() -> None:
    assert ccm.check_message("Merge branch 'x'\n", _project(), (MOON,)) == []


def test_main_with_no_framework_toml_accepts_the_owner_alone(tmp_path: Path, capsys) -> None:
    root = _root(tmp_path)
    assert ccm.main(["--root", str(root), str(_message(tmp_path, f"Add\n\n{SIGNOFF}\n"))]) == 0
    assert ccm.main(["--root", str(root), str(_message(tmp_path, f"Add\n\n{MOON_SIGNOFF}\n"))]) == 1
    assert "Moon" not in capsys.readouterr().err


def test_main_with_a_roster_accepts_a_roster_person(tmp_path: Path, capsys) -> None:
    root = _roster_root(tmp_path, OWNER_ROW, MOON)
    assert ccm.main(["--root", str(root), str(_message(tmp_path, f"Add\n\n{MOON_SIGNOFF}\n"))]) == 0
    assert ccm.main(["--root", str(root), str(_message(tmp_path, f"Add\n\n{SIGNOFF}\n"))]) == 0
    assert capsys.readouterr().err == ""


def test_main_with_an_invalid_framework_toml_cannot_run(tmp_path: Path, capsys) -> None:
    """A roster with no owner is refused by the loader; the hook stops with the reason and judges nothing."""
    root = _roster_root(tmp_path, OWNER_ROW, MOON)  # the dumper refuses an ownerless roster, so demote the owner after
    toml = root / "framework.toml"
    toml.write_text(
        toml.read_text(encoding="utf-8").replace('role = "owner"', 'role = "contributor"'), encoding="utf-8"
    )
    assert ccm.main(["--root", str(root), str(_message(tmp_path, f"Add\n\n{MOON_SIGNOFF}\n"))]) == 2
    err = capsys.readouterr().err
    assert "cannot run" in err and "owner" in err and "[commit-msg]" not in err


def test_main_with_an_unreadable_framework_toml_cannot_run(tmp_path: Path, capsys) -> None:
    """A directory of that name exists and cannot be read: an error, never 'no roster'."""
    root = _root(tmp_path)
    (root / "framework.toml").mkdir()
    assert ccm.main(["--root", str(root), str(_message(tmp_path, f"Add\n\n{SIGNOFF}\n"))]) == 2
    assert "cannot run" in capsys.readouterr().err


def test_verbose_counts_the_accepted_identities(tmp_path: Path) -> None:
    root = _roster_root(tmp_path, OWNER_ROW, MOON)
    base = [sys.executable, str(ROOT / "tools" / "check_commit_msg.py"), "--root", str(root), "-v"]
    loud = subprocess.run([*base, str(_message(tmp_path, f"Add\n\n{MOON_SIGNOFF}\n"))], capture_output=True, text=True)
    assert loud.returncode == 0 and "accepted identities: 3" in loud.stderr


def test_the_script_runs_as_the_hook_runs_it_with_a_roster(tmp_path: Path) -> None:
    root = _roster_root(tmp_path, OWNER_ROW, MOON)
    script = ROOT / "tools" / "check_commit_msg.py"
    good = _message(tmp_path, f"Add\n\n{MOON_SIGNOFF}\n")
    assert subprocess.run([sys.executable, str(script), "--root", str(root), str(good)], check=False).returncode == 0
    bad = _message(tmp_path, "Add\n\nSigned-off-by: Someone Else <else@example.org>\n")
    ran = subprocess.run([sys.executable, str(script), "--root", str(root), str(bad)], capture_output=True, text=True)
    assert ran.returncode == 1 and "Moon Mulligan <moon@example.org>" in ran.stderr and "Ada Example" in ran.stderr

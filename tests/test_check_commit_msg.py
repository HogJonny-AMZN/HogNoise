def _root(tmp_path: Path, signoff: bool = True) -> Path:
    (tmp_path / "project.json").write_text(fc.dump_project(_project(signoff)), encoding="utf-8")
    return tmp_path


def _message(tmp_path: Path, text: str) -> Path:
    path = tmp_path / "COMMIT_EDITMSG"
    path.write_text(text, encoding="utf-8")
    return path



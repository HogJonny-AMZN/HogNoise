def session(summary: str | None = "Did a thing.", by: str = "ada") -> str:
    head = "# Session\n\n**Status:** Living.\n"
    if summary is not None:
        head += f"**Summary:** {summary}\n"
    return head + f"\n### A heading\n**By:** @{by} · **Agent:** none\n\nProse.\n"


def make_repo(tmp: Path, files: dict[str, str], *, extra: str = "") -> Path:
    for rel, text in {**files, "framework.toml": FRAMEWORK.format(extra=extra)}.items():
        path = tmp / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return tmp


def page_of(root: Path) -> str:
    return (root / "Docs/journal/INDEX.md").read_text(encoding="utf-8")


def run(root: Path, *args: str) -> int:
    return rji.main([*args, "--root", str(root)])


def rows(text: str) -> list[list[str]]:
    table = [line for line in text.splitlines() if line.startswith("| ") and not line.startswith("| ---")]
    return [[cell.strip() for cell in line.strip("|").split(" | ")] for line in table][1:]



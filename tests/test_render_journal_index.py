def test_the_page_lists_new_form_files_newest_first_and_only_those(tmp_path: Path) -> None:
    root = make_repo(
        tmp_path,
        {
            "Docs/journal/2026-10-11-session-01.md": "# Old\n",
            "Docs/journal/2026-10/2026-10-11-ada-0930.md": session("First."),
            "Docs/journal/2026-10/2026-10-12-bo-b-0800.md": session("Second.", by="bo-b"),
            "Docs/journal/2026-10/2026-10-12-ada-0800.md": session("Third."),
            "Docs/journal/2026-10/2026-10-12-ada-0801.md": session("Fourth."),
            "Docs/journal/README.md": "# Journal\n",
            "Docs/journal/notes.md": "# Not a session\n",
        },
    )
    assert run(root) == 0
    got = rows(page_of(root))
    assert [r[3] for r in got] == [
        "[Fourth.](2026-10/2026-10-12-ada-0801.md)",
        "[Second.](2026-10/2026-10-12-bo-b-0800.md)",
        "[Third.](2026-10/2026-10-12-ada-0800.md)",
        "[First.](2026-10/2026-10-11-ada-0930.md)",
    ]
    assert got[0][:3] == ["2026-10-12", "08:01", "@ada"]
    assert got[1][:3] == ["2026-10-12", "08:00", "@bo-b"]



def git(root: Path, *args: str, who: str = "ada@example.org") -> None:
    env = {**os.environ, "GIT_AUTHOR_NAME": "A", "GIT_AUTHOR_EMAIL": who, "GIT_COMMITTER_NAME": "A"}
    env["GIT_COMMITTER_EMAIL"] = who
    subprocess.run([GIT, *args], cwd=root, env=env, check=True, capture_output=True)


def committed(root: Path, name: str, who: str, text: str | None = None) -> None:
    path = root / "Docs/journal" / name[:7] / name  # a new-form file lives in its month folder
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text or session(), encoding="utf-8", newline="\n")
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", f"add {name}", who=who)


